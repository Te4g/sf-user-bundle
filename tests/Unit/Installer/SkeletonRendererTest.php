<?php

declare(strict_types=1);

namespace Te4g\UserBundle\Tests\Unit\Installer;

use PHPUnit\Framework\TestCase;
use Te4g\UserBundle\Exception\InstallerConflict;
use Te4g\UserBundle\Installer\ProjectLayout;
use Te4g\UserBundle\Installer\SkeletonRenderer;

final class SkeletonRendererTest extends TestCase
{
    private string $projectDir;

    protected function setUp(): void
    {
        $this->projectDir = sys_get_temp_dir().'/te4g-user-skeleton-'.bin2hex(random_bytes(8));
        mkdir($this->projectDir, 0777, true);
    }

    protected function tearDown(): void
    {
        $this->remove($this->projectDir);
    }

    public function testGeneratedUserAndSecurityConfigUseApprovedContracts(): void
    {
        $files = (new SkeletonRenderer())->renderAll(ProjectLayout::at($this->projectDir));

        self::assertSame([
            'config/packages/reset_password.yaml',
            'config/packages/te4g_user.yaml',
            'config/packages/te4g_user_security.yaml',
            'config/packages/te4g_user_twig.yaml',
            'config/packages/verify_email.yaml',
            'config/routes/te4g_user.yaml',
            'src/Entity/ResetPasswordRequest.php',
            'src/Entity/User.php',
            'src/Repository/ResetPasswordRequestRepository.php',
            'src/Repository/UserRepository.php',
        ], array_slice(array_keys($files), 0, 10));
        self::assertArrayHasKey('templates/components/Card.html.twig', $files);
        self::assertArrayHasKey('templates/bundles/Te4gUserBundle/security/login.html.twig', $files);
        self::assertArrayHasKey('assets/controllers/password_visibility_controller.js', $files);
        self::assertStringContainsString('final class User implements AccountUserInterface', $files['src/Entity/User.php']);
        self::assertStringContainsString('enabled: true', $files['config/packages/te4g_user.yaml']);
        self::assertStringContainsString('check_post_only: true', $files['config/packages/te4g_user_security.yaml']);
        self::assertStringContainsString('max_uses: 1', $files['config/packages/te4g_user_security.yaml']);
        self::assertStringContainsString('lifetime: 600', $files['config/packages/te4g_user_security.yaml']);
        self::assertDoesNotMatchRegularExpression('/__[A-Z_]+__/', implode("\n", $files));
    }

    #[\PHPUnit\Framework\Attributes\DataProvider('projectSourceVariants')]
    public function testApplicationNamespaceFromComposerIsSubstitutedForSafeProjectSourceVariants(string $sourceDirectory): void
    {
        file_put_contents($this->projectDir.'/composer.json', json_encode([
            'autoload' => ['psr-4' => ['Acme\\Portal\\' => $sourceDirectory]],
        ], JSON_THROW_ON_ERROR));

        $files = (new SkeletonRenderer('9.8.7'))->renderAll(ProjectLayout::at($this->projectDir));

        self::assertStringContainsString('namespace Acme\Portal\Entity;', $files['src/Entity/User.php']);
        self::assertStringContainsString('namespace Acme\Portal\Repository;', $files['src/Repository/UserRepository.php']);
        self::assertStringContainsString('user_class: Acme\Portal\Entity\User', $files['config/packages/te4g_user.yaml']);
        self::assertStringContainsString('account_repository: Acme\Portal\Repository\UserRepository', $files['config/packages/te4g_user.yaml']);
        self::assertStringContainsString('# Generated by te4g/user-bundle 9.8.7', $files['config/packages/te4g_user.yaml']);
    }

    /** @return iterable<string, array{string}> */
    public static function projectSourceVariants(): iterable
    {
        yield 'bare' => ['src'];
        yield 'trailing slash' => ['src/'];
        yield 'leading dot' => ['./src'];
        yield 'repeated separators' => ['.//src///'];
        yield 'multiple leading dots' => ['././src'];
        yield 'trailing dot' => ['src/./'];
        yield 'windows dot segments' => ['.\\.\\src'];
        yield 'leading and trailing dots' => ['./src/./'];
    }

    public function testApplicationNamespaceCanMapProjectSrcAmongMultipleDirectories(): void
    {
        file_put_contents($this->projectDir.'/composer.json', <<<'JSON'
            {"autoload":{"psr-4":{"Acme\\Portal\\":["lib/","./src/"]}}}
            JSON);

        $files = (new SkeletonRenderer())->renderAll(ProjectLayout::at($this->projectDir));

        self::assertStringContainsString('namespace Acme\Portal\Entity;', $files['src/Entity/User.php']);
    }

    /** @param array<string, mixed> $composer */
    #[\PHPUnit\Framework\Attributes\DataProvider('unsupportedComposerMappings')]
    public function testExistingComposerWithoutOneSafeProjectSrcNamespaceFailsClosed(array $composer): void
    {
        file_put_contents($this->projectDir.'/composer.json', json_encode($composer, JSON_THROW_ON_ERROR));

        $this->expectException(InstallerConflict::class);
        $this->expectExceptionMessage('Invalid installer project configuration.');

        (new SkeletonRenderer())->renderAll(ProjectLayout::at($this->projectDir));
    }

    /** @return iterable<string, array{array<string, mixed>}> */
    public static function unsupportedComposerMappings(): iterable
    {
        yield 'autoload absent' => [['name' => 'acme/portal']];
        yield 'psr-4 absent' => [['autoload' => ['classmap' => ['src/']]]];
        yield 'no src mapping' => [['autoload' => ['psr-4' => ['Acme\\Portal\\' => 'lib/']]]];
        yield 'leading parent traversal' => [['autoload' => ['psr-4' => ['Acme\\Portal\\' => '../src']]]];
        yield 'parent traversal' => [['autoload' => ['psr-4' => ['Acme\\Portal\\' => 'src/../src']]]];
        yield 'trailing parent traversal' => [['autoload' => ['psr-4' => ['Acme\\Portal\\' => 'src/..']]]];
        yield 'unix absolute' => [['autoload' => ['psr-4' => ['Acme\\Portal\\' => '/src']]]];
        yield 'windows absolute' => [['autoload' => ['psr-4' => ['Acme\\Portal\\' => 'C:\\src']]]];
        yield 'ambiguous namespaces' => [[
            'autoload' => [
                'psr-4' => [
                    'Acme\\Portal\\' => 'src/',
                    'Acme\\Shared\\' => './src/',
                ],
            ],
        ]];
    }

    public function testUnknownTemplateTokenIsRejectedInsteadOfLeakingIntoApplicationFiles(): void
    {
        $resourceDirectory = $this->copySkeleton();
        file_put_contents($resourceDirectory.'/config/packages/te4g_user.yaml.tpl', "te4g_user:\n    enabled: true\n__UNAPPROVED_TOKEN__\n");

        $this->expectException(\LogicException::class);
        $this->expectExceptionMessage('Unresolved skeleton token');

        (new SkeletonRenderer('0.1.0', $resourceDirectory))->renderAll(ProjectLayout::at($this->projectDir));
    }

    public function testInvalidApplicationNamespaceCannotInjectGeneratedPhp(): void
    {
        file_put_contents($this->projectDir.'/composer.json', <<<'JSON'
            {"autoload":{"psr-4":{"App; phpinfo(); //\\":"src/"}}}
            JSON);

        $this->expectException(InstallerConflict::class);
        $this->expectExceptionMessage('Invalid installer project configuration.');

        (new SkeletonRenderer())->renderAll(ProjectLayout::at($this->projectDir));
    }

    private function copySkeleton(): string
    {
        $target = $this->projectDir.'/skeleton';
        $source = dirname(__DIR__, 3).'/resources/skeleton';
        $iterator = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator($source, \FilesystemIterator::SKIP_DOTS),
            \RecursiveIteratorIterator::SELF_FIRST,
        );

        foreach ($iterator as $item) {
            $destination = $target.'/'.substr($item->getPathname(), strlen($source) + 1);
            if ($item->isDir()) {
                mkdir($destination, 0777, true);
            } else {
                copy($item->getPathname(), $destination);
            }
        }

        return $target;
    }

    private function remove(string $path): void
    {
        if (!file_exists($path)) {
            return;
        }

        if (!is_dir($path)) {
            unlink($path);

            return;
        }

        foreach (scandir($path) ?: [] as $entry) {
            if ('.' === $entry || '..' === $entry) {
                continue;
            }

            $this->remove($path.'/'.$entry);
        }

        rmdir($path);
    }
}
