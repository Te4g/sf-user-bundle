    /**
     * Synchronize files generated by a real UX Toolkit fixture.
     *
     * UX Toolkit 3.3 accepts one recipe per ux:install invocation. The caller
     * must run the eight fixed commands before invoking this synchronizer.
     *
     * @param list<string> $recipes
     *
     * @return array{
     *     schema_version: int,
     *     generated_by: string,
     *     upstream: array{package: string, version: string, reference: string, license: string},
     *     recipes: list<string>,
     *     compatibility: string,
     *     icons: array{package: string, version: string, license: string, names: list<string>},
     *     files: list<array{path: string, source: string, license: string, sha256: string, local_modification?: string}>
     * }
     */
    public function synchronize(string $projectRoot, string $destinationRoot, array $recipes = self::ALLOWED_RECIPES): array
    {
        $sourceRoot = $this->realDirectory($projectRoot, 'temporary project root');
        $destinationRoot = rtrim($destinationRoot, DIRECTORY_SEPARATOR);
        [$resourcesDirectory, $destinationBoundary] = $this->normalizePendingDirectory(dirname($destinationRoot));
        $destinationRoot = $resourcesDirectory.'/'.$this->safeRelativePath(basename($destinationRoot));
        $manifestDirectory = $resourcesDirectory.'/shadcn';
        $manifestPath = $manifestDirectory.'/manifest.json';
        $this->assertPendingPath($destinationRoot, $destinationBoundary, 'snapshot destination');
        $this->assertPendingPath($manifestDirectory, $destinationBoundary, 'Shadcn manifest directory');
        $this->assertPendingPath($manifestPath, $destinationBoundary, 'Shadcn manifest');

        $recipes = $this->validateRecipes($recipes);
        $package = $this->toolkitPackage($sourceRoot);
        $planned = [];
        $visited = [];

        foreach ($recipes as $recipe) {
            $this->collectRecipeFiles($sourceRoot, $recipe, $visited, $planned);
        }

        foreach (self::FIXED_ICONS as $icon) {
            $path = 'assets/icons/lucide/'.$icon.'.svg';
            $contents = $this->readExistingFileInside($sourceRoot.'/'.$path, $sourceRoot, 'installed icon');
            $planned[$path] = [
                'contents' => $contents,
                'record' => [
                    'path' => $path,
                    'source' => '@iconify-json/lucide@1.2.121',
                    'license' => 'ISC',
                    'sha256' => hash('sha256', $contents),
                ],
            ];
        }

        ksort($planned, SORT_STRING);
        $manifest = [
            'schema_version' => 1,
            'generated_by' => 'tools/ShadcnSnapshotSynchronizer.php',
            'upstream' => [
                'package' => 'symfony/ux-toolkit',
                'version' => ltrim($package['version'], 'v'),
                'reference' => $package['reference'],
                'license' => $package['license'],
            ],
            'recipes' => $recipes,
            'compatibility' => 'UX Toolkit 3.3 accepts one recipe per ux:install command; the fixed recipes are installed sequentially.',
            'icons' => [
                'package' => '@iconify-json/lucide',
                'version' => '1.2.121',
                'license' => 'ISC',
                'names' => self::FIXED_ICONS,
            ],
            'files' => array_values(array_map(static fn (array $file): array => $file['record'], $planned)),
        ];
        $manifestJson = json_encode($manifest, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR)."\n";

        $this->commitSnapshot($destinationRoot, $manifestPath, $planned, $manifestJson, $destinationBoundary);

        return $manifest;
    }

    /** @param list<string> $recipes
     * @return list<string>
     */
    private function validateRecipes(array $recipes): array
    {
        $validated = [];
        foreach ($recipes as $recipe) {
            if (!is_string($recipe) || !in_array($recipe, self::ALLOWED_RECIPES, true)) {
                throw new \InvalidArgumentException(sprintf('Unsupported Shadcn recipe "%s".', is_scalar($recipe) ? (string) $recipe : get_debug_type($recipe)));
            }

            if (!in_array($recipe, $validated, true)) {
                $validated[] = $recipe;
            }
        }

        return $validated;
    }

    /**
     * @param array<string, true> $visited
     * @param array<string, array{
     *     contents: string,
     *     record: array{path: string, source: string, license: string, sha256: string, local_modification?: string}
     * }> $planned
     */
    private function collectRecipeFiles(string $sourceRoot, string $recipe, array &$visited, array &$planned): void
    {
        if (!in_array($recipe, self::ALLOWED_DEPENDENCY_RECIPES, true)) {
            throw new \RuntimeException(sprintf('Recipe "%s" is outside the pinned UX Toolkit 3.3.0 fixed dependency closure.', $recipe));
        }

        if (isset($visited[$recipe])) {
            return;
        }

        $visited[$recipe] = true;
        $recipeRoot = $this->realDirectory(
            $sourceRoot.'/vendor/symfony/ux-toolkit/kits/shadcn/'.$this->safeRelativePath($recipe),
            'recipe root',
        );
        $manifestPath = $recipeRoot.'/manifest.json';
        $manifest = json_decode($this->readExistingFileInside($manifestPath, $sourceRoot, 'recipe manifest'), true, flags: JSON_THROW_ON_ERROR);

        if (!is_array($manifest)) {
            throw new \RuntimeException(sprintf('Invalid manifest for Shadcn recipe "%s".', $recipe));
        }

        $dependencies = $manifest['dependencies']['recipe'] ?? [];
        if (!is_array($dependencies)) {
            throw new \RuntimeException(sprintf('Invalid recipe dependencies for "%s".', $recipe));
        }

        foreach ($dependencies as $dependency) {
            if (!is_string($dependency) || !in_array($dependency, self::ALLOWED_DEPENDENCY_RECIPES, true)) {
                throw new \RuntimeException('Recipe dependency is outside the pinned UX Toolkit 3.3.0 fixed dependency closure.');
            }

            $this->collectRecipeFiles($sourceRoot, $dependency, $visited, $planned);
        }

        $copyFiles = $manifest['copy-files'] ?? null;
        if (!is_array($copyFiles)) {
            throw new \RuntimeException(sprintf('Recipe "%s" has no copy-files map.', $recipe));
        }

        foreach ($copyFiles as $from => $to) {
            if (!is_string($from) || !is_string($to)) {
                throw new \RuntimeException('Unsafe snapshot path in recipe copy map.');
            }

            $from = $this->safeRelativePath($from);
            $to = $this->safeRelativePath($to);
            $recipeSource = $this->realDirectory($recipeRoot.'/'.$from, 'recipe copy source');
            $iterator = new \RecursiveIteratorIterator(
                new \RecursiveDirectoryIterator($recipeSource, \FilesystemIterator::SKIP_DOTS),
            );

            /** @var \SplFileInfo $item */
            foreach ($iterator as $item) {
                if (!$item->isFile()) {
                    continue;
                }

                $upstreamPath = $item->getPathname();
                $upstream = $this->readExistingFileInside($upstreamPath, $sourceRoot, 'recipe source');
                $suffix = substr($upstreamPath, strlen($recipeSource) + 1);
                $targetPath = $this->safeRelativePath($to.'/'.$suffix);
                $installed = $this->readExistingFileInside($sourceRoot.'/'.$targetPath, $sourceRoot, 'installed source');
                if (!hash_equals(hash('sha256', $upstream), hash('sha256', $installed))) {
                    throw new \RuntimeException(sprintf('Installed recipe file "%s" differs from the pinned upstream recipe.', $targetPath));
                }

                [$contents, $localModification] = $this->adapt($targetPath, $installed);
                $record = [
                    'path' => $targetPath,
                    'source' => 'symfony/ux-toolkit:shadcn/'.$recipe,
                    'license' => 'MIT',
                    'sha256' => hash('sha256', $contents),
                ];
                if (null !== $localModification) {
                    $record['local_modification'] = $localModification;
                }

                $planned[$targetPath] = ['contents' => $contents, 'record' => $record];
            }
        }
    }

    /** @return array{string, ?string} */
    private function adapt(string $path, string $contents): array
    {
        if (!isset(self::ADAPTATIONS[$path])) {
            return [$contents, null];
        }

        $adaptation = self::ADAPTATIONS[$path];
        if (!hash_equals($adaptation['before'], hash('sha256', $contents))) {
            throw new \RuntimeException(sprintf('Pinned pre-patch hash mismatch for "%s".', $path));
        }

        $transform = $adaptation['transform'];
        $adapted = $this->{$transform}($contents);
        if (!hash_equals($adaptation['after'], hash('sha256', $adapted))) {
            throw new \LogicException(sprintf('Deterministic local adaptation for "%s" produced an unexpected hash.', $path));
        }

        return [$adapted, $adaptation['description']];
    }

    private function adaptAlertDialogController(string $contents): string
    {
        $contents = $this->replaceOnce(
            $contents,
            "static targets = ['trigger', 'dialog'];",
            "static targets = ['trigger', 'dialog', 'form'];",
        );
        $start = strpos($contents, "    open() {\n");
        if (false === $start) {
            throw new \RuntimeException('Unable to apply the alert dialog controller adaptation.');
        }

        return substr($contents, 0, $start).<<<'JS'
                disconnect() {
                    if (this.hasDialogTarget && this.dialogTarget.open) {
                        this.dialogTarget.close();
                    }

                    if (this.hasTriggerTarget) {
                        this.triggerTarget.setAttribute('aria-expanded', 'false');
                    }
                }

                open() {
                    this.dialogTarget.showModal();
                    this.triggerTarget.setAttribute('aria-expanded', 'true');
                }

                close() {
                    this.dialogTarget.close();
                    this.triggerTarget.setAttribute('aria-expanded', 'false');
                    this.triggerTarget.focus();
                }

                submit() {
                    this.close();
                    this.formTarget.requestSubmit();
                }
            }
            JS."\n";
    }

    private function adaptAlertDialogRoot(string $contents): string
    {
        return $this->replaceOnce(
            $contents,
            "    'data-alert-dialog-open-value': open,\n    'aria-labelledby': _alertDialog_titleId,\n    'aria-describedby': _alertDialog_descriptionId,",
            "    'data-alert-dialog-open-value': open,",
        );
    }

    private function adaptAlertDialogContent(string $contents): string
    {
        $contents = $this->replaceOnce(
            $contents,
            "{%- set _alertDialog_id = inject('alertDialog.id') -%}\n",
            "{%- set _alertDialog_id = inject('alertDialog.id') -%}\n{%- set _alertDialog_titleId = inject('alertDialog.titleId') -%}\n{%- set _alertDialog_descriptionId = inject('alertDialog.descriptionId') -%}\n",
        );

        return $this->replaceOnce(
            $contents,
            "    id=\"{{ _alertDialog_id }}\"\n",
            "    id=\"{{ _alertDialog_id }}\"\n    aria-labelledby=\"{{ _alertDialog_titleId }}\"\n    aria-describedby=\"{{ _alertDialog_descriptionId }}\"\n",
        );
    }

    private function adaptSpinner(string $contents): string
    {
        $start = strpos($contents, '{%- props');
        if (false === $start) {
            throw new \RuntimeException('Unable to apply the spinner adaptation.');
        }

        return substr($contents, 0, $start).<<<'TWIG'
            {# Locally modified to remain fully offline with the bundle's fixed icon allowlist. #}
            {%- props label = 'Loading' -%}
            <svg
                viewBox="0 0 24 24"
                fill="none"
                xmlns="http://www.w3.org/2000/svg"
                data-slot="spinner"
                role="status"
                aria-label="{{ label }}"
                class="{{ ('size-4 animate-spin ' ~ attributes.render('class'))|tailwind_merge }}"
                {{ attributes.without('class') }}
            >
                <circle cx="12" cy="12" r="9" stroke="currentColor" stroke-opacity="0.25" stroke-width="3" />
                <path d="M21 12a9 9 0 0 0-9-9" stroke="currentColor" stroke-linecap="round" stroke-width="3" />
            </svg>
            TWIG."\n";
    }

    private function replaceOnce(string $contents, string $search, string $replacement): string
    {
        if (1 !== substr_count($contents, $search)) {
            throw new \RuntimeException('Pinned patch context does not match exactly once.');
        }

        return str_replace($search, $replacement, $contents);
    }

    /**
     * @param array<string, array{
     *     contents: string,
     *     record: array{path: string, source: string, license: string, sha256: string, local_modification?: string}
     * }> $planned
     */
    private function commitSnapshot(
        string $destinationRoot,
        string $manifestPath,
        array $planned,
        string $manifestJson,
        string $boundary,
    ): void {
        $stage = $boundary.'/.te4g-shadcn-stage-'.bin2hex(random_bytes(12));
        if (!mkdir($stage, 0700)) {
            throw new \RuntimeException('Unable to create the Shadcn staging directory.');
        }

        $committed = [];
        $createdDirectories = [];

        try {
            foreach ($planned as $path => $file) {
                $stagedPath = $stage.'/files/'.$path;
                $this->writeStagedFile($stagedPath, $file['contents']);
            }
            $stagedManifest = $stage.'/manifest.json';
            $this->writeStagedFile($stagedManifest, $manifestJson);

            $this->assertPendingPath($destinationRoot, $boundary, 'snapshot destination');
            $this->assertPendingPath($manifestPath, $boundary, 'Shadcn manifest');

            foreach (array_keys($planned) as $path) {
                $this->installStagedFile(
                    $stage.'/files/'.$path,
                    $destinationRoot.'/'.$path,
                    $boundary,
                    $stage,
                    $committed,
                    $createdDirectories,
                );
            }
            $this->installStagedFile(
                $stagedManifest,
                $manifestPath,
                $boundary,
                $stage,
                $committed,
                $createdDirectories,
            );
        } catch (\Throwable $failure) {
            $this->rollback($committed, $createdDirectories);

            throw $failure;
        } finally {
            $this->removeTree($stage);
        }
    }

    private function writeStagedFile(string $path, string $contents): void
    {
        if (!is_dir(dirname($path)) && !mkdir(dirname($path), 0700, true) && !is_dir(dirname($path))) {
            throw new \RuntimeException('Unable to create a Shadcn staging path.');
        }

        $handle = fopen($path, 'x+b');
        if (false === $handle) {
            throw new \RuntimeException('Unable to create a staged Shadcn file without clobbering.');
        }

        try {
            if (strlen($contents) !== fwrite($handle, $contents) || !fflush($handle)) {
                throw new \RuntimeException('Unable to write a complete staged Shadcn file.');
            }
        } finally {
            fclose($handle);
        }
    }

    /**
     * @param list<array{target: string, backup: ?string}> $committed
     * @param list<string>                                 $createdDirectories
     */
    private function installStagedFile(
        string $staged,
        string $target,
        string $boundary,
        string $stage,
        array &$committed,
        array &$createdDirectories,
    ): void {
        $this->assertPendingPath($target, $boundary, str_ends_with($target, '/manifest.json') ? 'Shadcn manifest' : 'snapshot file');
        $this->ensureDirectory(dirname($target), $boundary, $createdDirectories);
        $this->assertPendingPath($target, $boundary, str_ends_with($target, '/manifest.json') ? 'Shadcn manifest' : 'snapshot file');

        $backup = null;
        if (file_exists($target)) {
            if (is_link($target) || !is_file($target)) {
                throw new \RuntimeException('Unsafe existing Shadcn target.');
            }

            $backup = $stage.'/backups/'.count($committed);
            if (!is_dir(dirname($backup)) && !mkdir(dirname($backup), 0700, true) && !is_dir(dirname($backup))) {
                throw new \RuntimeException('Unable to create a Shadcn backup path.');
            }
            if (!rename($target, $backup)) {
                throw new \RuntimeException('Unable to stage the existing Shadcn target for replacement.');
            }
        }

        if (!rename($staged, $target)) {
            if (null !== $backup) {
                rename($backup, $target);
            }

            throw new \RuntimeException('Unable to atomically install a staged Shadcn file.');
        }

        $committed[] = ['target' => $target, 'backup' => $backup];
    }

    /**
     * @param list<array{target: string, backup: ?string}> $committed
     * @param list<string>                                 $createdDirectories
     */
    private function rollback(array $committed, array $createdDirectories): void
    {
        foreach (array_reverse($committed) as $file) {
            if (is_file($file['target']) && !is_link($file['target'])) {
                unlink($file['target']);
            }
            if (null !== $file['backup'] && is_file($file['backup'])) {
                rename($file['backup'], $file['target']);
            }
        }

        foreach (array_reverse($createdDirectories) as $directory) {
            if (is_dir($directory) && [] === array_diff(scandir($directory) ?: [], ['.', '..'])) {
                rmdir($directory);
            }
        }
    }

    /** @param list<string> $createdDirectories */
    private function ensureDirectory(string $path, string $boundary, array &$createdDirectories): void
    {
        $this->assertPendingPath($path, $boundary, 'snapshot directory');
        $relative = ltrim(substr($path, strlen($boundary)), DIRECTORY_SEPARATOR);
        $current = $boundary;
        foreach (array_filter(explode(DIRECTORY_SEPARATOR, $relative), static fn (string $part): bool => '' !== $part) as $part) {
            $current .= DIRECTORY_SEPARATOR.$part;
            if (is_link($current)) {
                throw new \RuntimeException('Snapshot directory escapes through a symlink.');
            }
            if (is_dir($current)) {
                continue;
            }
            if (file_exists($current) || !mkdir($current, 0777)) {
                throw new \RuntimeException('Unable to create a snapshot directory safely.');
            }
            $createdDirectories[] = $current;
        }
    }

    /** @return array{version: string, reference: string, license: string} */
    private function toolkitPackage(string $sourceRoot): array
    {
        $installed = json_decode(
            $this->readExistingFileInside($sourceRoot.'/vendor/composer/installed.json', $sourceRoot, 'Composer installed metadata'),
            true,
            flags: JSON_THROW_ON_ERROR,
        );
        $packages = is_array($installed) && isset($installed['packages']) && is_array($installed['packages'])
            ? $installed['packages']
            : $installed;

        if (!is_array($packages)) {
            throw new \RuntimeException('Invalid Composer installed metadata.');
        }

        foreach ($packages as $package) {
            if (!is_array($package) || 'symfony/ux-toolkit' !== ($package['name'] ?? null)) {
                continue;
            }

            $version = $package['version'] ?? null;
            $reference = $package['source']['reference'] ?? $package['dist']['reference'] ?? null;
            $license = $package['license'][0] ?? null;
            if (!is_string($version) || !is_string($reference) || !is_string($license)) {
                break;
            }
            if (self::TOOLKIT_VERSION !== ltrim($version, 'v') || self::TOOLKIT_REFERENCE !== $reference || 'MIT' !== $license) {
                throw new \RuntimeException('The synchronizer requires the pinned symfony/ux-toolkit 3.3.0 source.');
            }

            return ['version' => $version, 'reference' => $reference, 'license' => $license];
        }

        throw new \RuntimeException('Unable to resolve the installed symfony/ux-toolkit package metadata.');
    }

    private function safeRelativePath(string $path): string
    {
        if ('' === $path || str_contains($path, "\0")) {
            throw new \RuntimeException('Unsafe snapshot path.');
        }

        $portable = str_replace('\\', '/', $path);
        if (str_starts_with($portable, '/') || 1 === preg_match('/^[A-Za-z]:\//', $portable)) {
            throw new \RuntimeException('Unsafe snapshot path.');
        }

        $segments = [];
        foreach (explode('/', $portable) as $segment) {
            if ('' === $segment || '.' === $segment) {
                continue;
            }
            if ('..' === $segment) {
                throw new \RuntimeException('Unsafe snapshot path.');
            }
            $segments[] = $segment;
        }

        if ([] === $segments) {
            throw new \RuntimeException('Unsafe snapshot path.');
        }

        return implode('/', $segments);
    }

    private function realDirectory(string $path, string $label): string
    {
        if (is_link($path) || false === ($resolved = realpath($path)) || !is_dir($resolved)) {
            throw new \RuntimeException(sprintf('Invalid %s.', $label));
        }

        return rtrim($resolved, DIRECTORY_SEPARATOR);
    }

    /** @return array{string, string} Normalized pending directory and nearest existing boundary. */
    private function normalizePendingDirectory(string $path): array
    {
        if ('' === $path || str_contains($path, "\0") || !str_starts_with($path, DIRECTORY_SEPARATOR)) {
            throw new \RuntimeException('Invalid snapshot destination parent.');
        }

        $segments = explode(DIRECTORY_SEPARATOR, $path);
        if (in_array('..', $segments, true)) {
            throw new \RuntimeException('Invalid snapshot destination parent.');
        }

        $missing = [];
        $cursor = rtrim($path, DIRECTORY_SEPARATOR);
        while (!file_exists($cursor) && !is_link($cursor)) {
            array_unshift($missing, basename($cursor));
            $parent = dirname($cursor);
            if ($parent === $cursor) {
                throw new \RuntimeException('Invalid snapshot destination parent.');
            }
            $cursor = $parent;
        }

        if (is_link($cursor) || !is_dir($cursor) || false === ($boundary = realpath($cursor))) {
            throw new \RuntimeException('Invalid snapshot destination parent.');
        }

        $normalized = rtrim($boundary, DIRECTORY_SEPARATOR);
        foreach ($missing as $segment) {
            $normalized .= DIRECTORY_SEPARATOR.$this->safeRelativePath($segment);
        }

        return [$normalized, rtrim($boundary, DIRECTORY_SEPARATOR)];
    }

    private function readExistingFileInside(string $path, string $root, string $label): string
    {
        if (is_link($path) || false === ($resolved = realpath($path)) || !is_file($resolved) || !$this->contains($resolved, $root)) {
            throw new \RuntimeException(sprintf('%s escapes the temporary project root.', ucfirst($label)));
        }

        $contents = file_get_contents($resolved);
        if (false === $contents) {
            throw new \RuntimeException(sprintf('Unable to read %s.', $label));
        }

        return $contents;
    }

    private function assertPendingPath(string $path, string $boundary, string $label): void
    {
        $boundary = rtrim($boundary, DIRECTORY_SEPARATOR);
        if (!$this->contains($path, $boundary)) {
            throw new \RuntimeException(sprintf('Unsafe %s path.', $label));
        }

        $relative = ltrim(substr($path, strlen($boundary)), DIRECTORY_SEPARATOR);
        $current = $boundary;
        foreach (array_filter(explode(DIRECTORY_SEPARATOR, $relative), static fn (string $part): bool => '' !== $part) as $part) {
            $current .= DIRECTORY_SEPARATOR.$part;
            if (is_link($current)) {
                if (str_contains(strtolower($label), 'manifest')) {
                    throw new \RuntimeException(sprintf('Unsafe %s symlink.', $label));
                }

                throw new \RuntimeException('Path escapes the snapshot destination through a symlink.');
            }
        }
    }

    private function contains(string $path, string $root): bool
    {
        $root = rtrim($root, DIRECTORY_SEPARATOR);

        return $path === $root || str_starts_with($path, $root.DIRECTORY_SEPARATOR);
    }

    private function removeTree(string $path): void
    {
        if (!is_dir($path) || is_link($path)) {
            if (file_exists($path) || is_link($path)) {
                unlink($path);
            }

            return;
        }

        $iterator = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator($path, \FilesystemIterator::SKIP_DOTS),
            \RecursiveIteratorIterator::CHILD_FIRST,
        );
        foreach ($iterator as $item) {
            if ($item->isDir() && !$item->isLink()) {
                rmdir($item->getPathname());
            } else {
                unlink($item->getPathname());
            }
        }
        rmdir($path);
    }
}
