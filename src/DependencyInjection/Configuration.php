<?php

declare(strict_types=1);

namespace Te4g\UserBundle\DependencyInjection;

use Symfony\Component\Config\Definition\Builder\ArrayNodeDefinition;
use Symfony\Component\Config\Definition\Builder\TreeBuilder;
use Symfony\Component\Config\Definition\ConfigurationInterface;

final class Configuration implements ConfigurationInterface
{
    public function getConfigTreeBuilder(): TreeBuilder
    {
        $treeBuilder = new TreeBuilder('te4g_user');

        /** @var ArrayNodeDefinition $rootNode */
        $rootNode = $treeBuilder->getRootNode();

        $rootNode
            ->children()
                ->booleanNode('enabled')
                    ->defaultFalse()
                ->end()
                ->scalarNode('user_class')
                    ->defaultValue('App\\Entity\\User')
                    ->cannotBeEmpty()
                ->end()
                ->scalarNode('account_repository')
                    ->defaultValue('App\\Repository\\UserRepository')
                    ->cannotBeEmpty()
                ->end()
                ->arrayNode('mailer')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('from_email')
                            ->defaultValue('no-reply@example.com')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('from_name')
                            ->defaultValue('Application')
                            ->cannotBeEmpty()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('redirects')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('login_success')
                            ->defaultValue('app_home')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('verified')
                            ->defaultValue('te4g_user_login')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('account_updated')
                            ->defaultValue('te4g_user_account')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('account_deleted')
                            ->defaultValue('app_home')
                            ->cannotBeEmpty()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('templates')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('registration')
                            ->defaultValue('@Te4gUser/registration/register.html.twig')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('login')
                            ->defaultValue('@Te4gUser/security/login.html.twig')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('login_link_check')
                            ->defaultValue('@Te4gUser/security/login_link_check.html.twig')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('check_email')
                            ->defaultValue('@Te4gUser/security/check_email.html.twig')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('password_request')
                            ->defaultValue('@Te4gUser/password/request.html.twig')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('password_reset')
                            ->defaultValue('@Te4gUser/password/reset.html.twig')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('account')
                            ->defaultValue('@Te4gUser/account/index.html.twig')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('profile')
                            ->defaultValue('@Te4gUser/account/profile.html.twig')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('password_change')
                            ->defaultValue('@Te4gUser/account/password.html.twig')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('verification_email')
                            ->defaultValue('@Te4gUser/email/verify.html.twig')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('magic_link_email')
                            ->defaultValue('@Te4gUser/email/magic_link.html.twig')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('password_reset_email')
                            ->defaultValue('@Te4gUser/email/password_reset.html.twig')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('email_change_email')
                            ->defaultValue('@Te4gUser/email/email_change.html.twig')
                            ->cannotBeEmpty()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('features')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('account_deletion')
                            ->defaultTrue()
                        ->end()
                    ->end()
                ->end()
            ->end()
        ;

        return $treeBuilder;
    }
}
